/** Runs whose observed identity departs from the profile's declaration (version 2 records). */
export function identityFindings(records: Record<string, any>[]) {
  const ids = (test: (r: Record<string, any>) => boolean) => records.filter(test).map(r => r.run_id as string).sort(compare);
  const sessions = (r: Record<string, any>) => r.sessions as { usage: Record<string, unknown> | null }[];
  return {
    tool_version_mismatch: ids(r => r.provenance.profile.observed?.tool_version !== null && r.provenance.profile.observed?.tool_version !== r.provenance.profile.declared.tool_version),
    tool_version_unobserved: ids(r => r.provenance.profile.observed?.tool_version === null),
    model_mismatch: ids(r => sessions(r).some(s => s.usage?.model_mismatch === true)),
    unrecognized_identity: ids(r => sessions(r).some(s => s.usage?.unrecognized_identity === true)),
  };
}

interface Summary { sources: string[]; n: number; median: number | null; min: number | null; max: number | null; counts?: Record<string, number> }

function median(values: number[]): number | null {
  if (!values.length) return null;
  const sorted = [...values].sort((a, b) => a - b);
  const middle = Math.floor(sorted.length / 2);
  const value = sorted.length % 2 ? sorted[middle] : (sorted[middle - 1] + sorted[middle]) / 2;
  return Math.round(value * 1e6) / 1e6;
}

function summarize(values: Value[]): Summary {
  const sources = [...new Set(values.map(v => v.source))].sort(compare);
  const present = values.filter(v => v.value !== null);
  if (present.some(v => typeof v.value === 'string')) {
    const counts: Record<string, number> = {};
    for (const v of present) counts[String(v.value)] = (counts[String(v.value)] ?? 0) + 1;
    return { sources, n: present.length, median: null, min: null, max: null, counts: Object.fromEntries(Object.entries(counts).sort(([a], [b]) => compare(a, b))) };
  }
  const numbers = present.map(v => v.value as number);
  return { sources, n: numbers.length, median: median(numbers), min: numbers.length ? Math.min(...numbers) : null, max: numbers.length ? Math.max(...numbers) : null };
}

function group(scores: RunScore[], pick: 'measures' | 'diagnostics') {
  const arms = new Map<string, RunScore[]>();
  for (const s of scores) {
    const key = [s.task, s.condition, s.profile].join('\0');
    arms.set(key, [...(arms.get(key) ?? []), s]);
  }
  return [...arms.entries()].sort(([a], [b]) => compare(a, b)).map(([, runs]) => {
    const names = [...new Set(runs.flatMap(r => Object.keys(r[pick])))].sort(compare);
    const completed = runs.filter(r => r.status === 'completed');
    return {
      task: runs[0].task, condition: runs[0].condition, profile: runs[0].profile,
      runs: runs.length, completed: completed.length, failed: runs.length - completed.length,
      measures: Object.fromEntries(names.map(name => [name, summarize(completed.map(r => r[pick][name]).filter(Boolean))])),
    };
  });
}

/** Sources actually recorded for a measure across arms (review B7): never the scorecard default. */
const recordedSources = (arms: any[], name: string) => [...new Set(arms.flatMap(a => (a.measures[name] as Summary | undefined)?.sources ?? []))].sort(compare);
const label = (arms: any[], name: string) => `${name} [${recordedSources(arms, name).join(', ') || definition(name)?.source}]`;
/** A cell names its own sources whenever the column mixes sources. */
const sourced = (arms: any[], name: string, s: Summary | undefined) =>
  recordedSources(arms, name).length > 1 && s?.sources.length ? `${cell(s)} [${s.sources.join(', ')}]` : cell(s);
const cell = (s: Summary | undefined) => !s ? '—' : s.counts ? Object.entries(s.counts).map(([k, v]) => `${k}: ${v}`).join(', ') || '—'
  : s.median === null ? '—' : `${s.median} (${s.min}–${s.max}, n=${s.n})`;

function markdown(report: Record<string, any>): string {
  const lines = [`# Benchmark report — ${report.plan.id}`, '', `Plan hash: \`${report.plan.hash}\`. Generated by keystone-bench from durable run records; rebuildable and non-authoritative.`, '',
    'Measures are labelled by source. `reported` values come from the agent tool and are never verified. Medians, with range and count, over completed runs.', ''];
  const primary = ([...new Set(report.arms.flatMap((a: any) => Object.keys(a.measures)))] as string[]).sort(compare);
  lines.push('## Scorecard (comparable across conditions)', '', `| Task | Condition | Profile | Runs | ${primary.map(m => label(report.arms, m)).join(' | ')} |`, `|${'---|'.repeat(4 + primary.length)}`);
  for (const a of report.arms) lines.push(`| ${a.task} | ${a.condition} | ${a.profile} | ${a.completed}/${a.runs} | ${primary.map(m => sourced(report.arms, m, a.measures[m])).join(' | ')} |`);
  if (report.composite) {
    lines.push('', '## Composite (weights declared in the plan)', '', `Weights: ${Object.entries(report.composite.weights).map(([k, v]) => `${k} × ${v}`).join(', ')}.`, '', '| Task | Condition | Profile | Composite |', '|---|---|---|---|');
    for (const a of report.arms) lines.push(`| ${a.task} | ${a.condition} | ${a.profile} | ${a.composite.value ?? `— (missing ${a.composite.missing.join(', ')})`} |`);
  }
  const diagnostics = ([...new Set(report.diagnostics.flatMap((a: any) => Object.keys(a.measures)))] as string[]).sort(compare);
  lines.push('', '## Condition-specific diagnostics (not compared across conditions; never weighted)', '');
  if (!diagnostics.length) lines.push('None.');
  else {
    lines.push(`| Task | Condition | Profile | ${diagnostics.map(m => label(report.diagnostics, m)).join(' | ')} |`, `|${'---|'.repeat(3 + diagnostics.length)}`);
    for (const a of report.diagnostics) lines.push(`| ${a.task} | ${a.condition} | ${a.profile} | ${diagnostics.map(m => sourced(report.diagnostics, m, a.measures[m])).join(' | ')} |`);
  }
  if (report.identity) {
    lines.push('', '## Agent identity (listed, never excluded)', '');
    for (const [key, runs] of Object.entries(report.identity as Record<string, string[]>)) lines.push(`- ${key.replace(/_/g, ' ')}: ${runs.length ? runs.join(', ') : 'none'}`);
  }
  return lines.join('\n') + '\n';
}

/** `keystone-bench report <plan>`: a balanced scorecard per arm; byte-identical on re-run. */
export async function report(planFile: string, root: string, work: string | undefined, repos?: string): Promise<Result> {
  const opened = await open('report', planFile, root, work, { repos, gates: ['pilot'] });
  if (!opened.context) return opened.result!;
  const { plan, where } = opened.context;
  const identity = { id: plan.spec.id, hash: plan.hash };
  const { scores, refused, records } = await computeScores(opened.context);
  if (refused.length) return { command: 'report', outcome: 'blocked', plan: identity, diagnostics: refused };
  const arms = group(scores, 'measures');
  const weights = plan.spec.composite?.weights;
  const withComposite = arms.map(a => {
    if (!weights) return a;
    const missing = Object.keys(weights).sort(compare).filter(m => typeof a.measures[m]?.median !== 'number');
    const value = missing.length ? null : Math.round(Object.entries(weights).reduce((s, [m, w]) => s + w * (a.measures[m].median as number), 0) * 1e6) / 1e6;
    return { ...a, composite: { value, missing } };
  });
  const body = {
    kind: 'keystone-bench-report', schema_version: 1, generated_by: 'keystone-bench', plan: identity, purpose: plan.spec.purpose,
    arms: withComposite, composite: weights ? { weights } : null, diagnostics: group(scores, 'diagnostics'),
    // Version 2 (TASK-0015 item 1): identity mismatches are listed, never excluded (intention-to-treat).
    ...(plan.version === 2 ? { identity: identityFindings(records.map(r => r.record)), ...(isPilot(plan) ? { non_evidence: true } : {}) } : {}),
  };
  for (const [name, contents] of [['report.json', serialize(body)], ['report.md', markdown(body)]] as const) {
    const failure = await writeVerified(path.join(where.analysis, name), contents, where.boundaries.analysis);
    if (failure) return { command: 'report', outcome: 'failed', plan: identity, diagnostics: failure.diagnostics };
  }
  return { command: 'report', outcome: 'reported', plan: identity, diagnostics: [], arms: withComposite.length, report: path.join(where.analysis, 'report.json') };
}
